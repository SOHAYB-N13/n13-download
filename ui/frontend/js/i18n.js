  t(key, fallback) {
    const dict = this.dict[this.lang] || {};
    if (dict[key] !== undefined) return dict[key];
    if (this.lang !== "en" && this.dict.en[key] !== undefined) return this.dict.en[key];
    return fallback !== undefined ? fallback : key;
  },

  setLang(lang) {
    const next = lang === "fa" ? "fa" : "en";
    if (this.lang === next) return;
    this.lang = next;
    document.documentElement.lang = next;
    document.documentElement.dir = next === "fa" ? "rtl" : "ltr";
    document.body.classList.toggle("rtl", next === "fa");
    this._notify();
  },

  onChange(fn) {
    if (typeof fn === "function") this.listeners.push(fn);
  },

  _notify() {
    this.listeners.forEach((fn) => {
      try { fn(this.lang); } catch (e) { console.error("i18n listener error:", e); }
    });
  },

  // Apply translations to static DOM. Supports:
  //   data-i18n          -> textContent
  //   data-i18n-ph       -> placeholder
  //   data-i18n-title    -> title
  //   data-i18n-aria-label -> aria-label
  //   data-i18n-tip      -> data-tip (CSS tooltips)
  apply(root) {
    const scope = root || document;
    scope.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = this.t(el.dataset.i18n, el.textContent);
    });
    scope.querySelectorAll("[data-i18n-ph]").forEach((el) => {
      el.setAttribute("placeholder", this.t(el.dataset.i18nPh, el.getAttribute("placeholder") || ""));
    });
    scope.querySelectorAll("[data-i18n-title]").forEach((el) => {
      el.setAttribute("title", this.t(el.dataset.i18nTitle, el.getAttribute("title") || ""));
    });
    scope.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
      el.setAttribute("aria-label", this.t(el.dataset.i18nAriaLabel, el.getAttribute("aria-label") || ""));
    });
    scope.querySelectorAll("[data-i18n-tip]").forEach((el) => {
      el.setAttribute("data-tip", this.t(el.dataset.i18nTip, el.getAttribute("data-tip") || ""));
    });
  },

  // Format a helper string with replacements.
  fmt(key, vars, fallback) {
    let s = this.t(key, fallback);
    if (vars) {
      Object.entries(vars).forEach(([k, v]) => {
        s = s.split(`{${k}}`).join(String(v));
      });
    }
    return s;
  },
